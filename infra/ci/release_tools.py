"""Release helpers for the GitHub Actions release workflow.

Usage::

    python -m infra.ci.release_tools check-version v1.1.0
    python -m infra.ci.release_tools matrix          # JSON list of functions
    python -m infra.ci.release_tools notes v1.1.0    # CHANGELOG section

Keeping this logic in Python (rather than shell inside YAML) means the
release path is unit-tested like the rest of the code.
"""

import json
import re
import sys
import tomllib
from pathlib import Path
from typing import Any

import yaml

TAG_PATTERN = re.compile(r"^v(\d+\.\d+\.\d+)$")


class ReleaseError(Exception):
    """A release precondition failed."""


def version_from_tag(tag: str) -> str:
    """Return ``1.2.3`` for tag ``v1.2.3``.

    Raises:
        ReleaseError: If the tag is not ``v`` followed by SemVer.
    """
    match = TAG_PATTERN.fullmatch(tag)
    if match is None:
        raise ReleaseError(f"tag {tag!r} is not of the form vMAJOR.MINOR.PATCH")
    return match.group(1)


def check_version(tag: str, pyproject: Path) -> str:
    """Ensure ``tag`` matches the project version in ``pyproject``.

    A mismatch means the tag was not created by ``cz bump`` on a release
    branch, so the workflow must not publish anything for it.

    Raises:
        ReleaseError: On a malformed tag or a version mismatch.
    """
    version = version_from_tag(tag)
    project_version = tomllib.loads(pyproject.read_text(encoding="utf-8"))["project"]["version"]
    if project_version != version:
        raise ReleaseError(f"tag {tag} does not match pyproject version {project_version}")
    return version


def function_matrix(stack: Path) -> list[dict[str, str]]:
    """List deployable functions from ``stack.yml`` for a build matrix."""
    data: dict[str, Any] = yaml.safe_load(stack.read_text(encoding="utf-8"))
    return [
        {"name": name, "lang": spec["lang"], "handler": spec["handler"]}
        for name, spec in sorted(data["functions"].items())
    ]


def image_registry(owner: str) -> str:
    """GitHub Container Registry prefix; GHCR requires lowercase names."""
    return f"ghcr.io/{owner.lower()}"


def release_notes(changelog: str, tag: str) -> str:
    """Return the CHANGELOG section for ``tag`` without its heading.

    Raises:
        ReleaseError: If the changelog has no section for the tag, which
            means it was not regenerated by commitizen for this release.
    """
    lines = changelog.splitlines()
    start = next((i for i, line in enumerate(lines) if line.startswith(f"## {tag} ")), None)
    if start is None:
        raise ReleaseError(f"CHANGELOG.md has no section for {tag}")
    end = next((i for i in range(start + 1, len(lines)) if lines[i].startswith("## ")), len(lines))
    return "\n".join(lines[start + 1 : end]).strip() + "\n"


def main(argv: list[str] | None = None) -> int:
    """Command-line entry point; prints results to stdout."""
    args = argv if argv is not None else sys.argv[1:]
    root = Path(__file__).resolve().parents[2]
    try:
        if args[:1] == ["check-version"] and len(args) == 2:
            sys.stdout.write(check_version(args[1], root / "pyproject.toml") + "\n")
        elif args == ["matrix"]:
            sys.stdout.write(json.dumps(function_matrix(root / "stack.yml")) + "\n")
        elif args[:1] == ["notes"] and len(args) == 2:
            changelog = (root / "CHANGELOG.md").read_text(encoding="utf-8")
            sys.stdout.write(release_notes(changelog, args[1]))
        elif args[:1] == ["registry"] and len(args) == 2:
            sys.stdout.write(image_registry(args[1]) + "\n")
        else:
            sys.stderr.write(
                "usage: release_tools check-version|notes TAG | matrix | registry OWNER\n"
            )
            return 2
    except ReleaseError as exc:
        sys.stderr.write(f"error: {exc}\n")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
